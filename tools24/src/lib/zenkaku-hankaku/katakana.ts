export function zenkakuKatakanaToHankaku(text: string): string {
  let result = '';
  for (const char of text) {
    result += ZENKAKU_TO_HANKAKU[char] ?? char;
  }
  return result;
}

export function hankakuKatakanaToZenkaku(text: string): string {
  let result = '';
  let i = 0;
  while (i < text.length) {
    // 2文字結合（濁点・半濁点）を先に試みる
    if (i + 1 < text.length) {
      const twoChars = text[i] + text[i + 1];
      if (twoChars in HANKAKU_DAKUTEN) {
        result += HANKAKU_DAKUTEN[twoChars];
        i += 2;
        continue;
      }
    }
    const char = text[i];
    result += HANKAKU_TO_ZENKAKU_SINGLE[char] ?? char;
    i++;
  }
  return result;
}
